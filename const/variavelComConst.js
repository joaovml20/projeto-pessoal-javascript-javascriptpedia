// Com a palavra const é possivel declarar variaveis constantes
//uma constante nada mais é que uma variavel que não pode ter o seu valor modificado e
// uma variavel por sua vez, é um local na memória para armazenar informações
//No javascript, as variaveis devem começar com número ou letra, após isso é permitido usar
// caracteres especias como underline "_" ou cifrão "$"
// um exemplo abaixo de uma declaração de uma variavel constante
const souUmaVariavel = "ola mundo"
// Acima esta a declaração da variavel souUmaVariavel com const, que ela por sua vez, armazenar um texto
// que é "ola mundo" e ela não pode ter o seu valor alterado para outro texto ou numero
// javascript diferencia maiusculo de minusculo e vise-versa, ou seja, se no programar tivesse
// outra variavel com o nome SouUmaVariavel seria diferente da variavel souUmaVariavel por conta do "S" maiusculo.
// Javascript usar o padrão de nomeação de variavel de camelCase
// onde a primeira palavra da variavel é minuscula e após ela
// a primeira letra das palavras subsequentes são maiusculas
// exemplo: souUMaVariavel = sou - Uma - Variavel